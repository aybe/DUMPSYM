    private void Test(string[] input, string[] expected)
    {
        var actual = input.OrderBy(x => x, NaturalStringComparer.Ordinal).ToArray();

        WriteLine("expected, actual, match");

        for (var i = 0; i < actual.Length; i++)
        {
            var e = expected[i];
            var a = actual[i];
            WriteLine($"{e,-32}{a,-32}{a == e}");
        }

        CollectionAssert.AreEqual(expected, actual);
    }
